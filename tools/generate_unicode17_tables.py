#!/usr/bin/env python3
"""Regenerate the tokenizer's frozen Unicode 17 tables from original UCD files.

Development-only, offline tool; neither builds nor runtime invoke Python or fetch
data. Supply a directory containing the three exact upstream files listed below
and the output Rust path. The tokenizer's named profiles consume these tables.
"""

import argparse
import hashlib
from pathlib import Path


SOURCES = {
    "UnicodeData.txt": "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c",
    "PropList.txt": "130dcddcaadaf071008bdfce1e7743e04fdfbc910886f017d9f9ac931d8c64dd",
    "CaseFolding.txt": "ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183",
}


def read_source(directory, name):
    raw = (directory / name).read_bytes()
    if hashlib.sha256(raw).hexdigest() != SOURCES[name]:
        raise ValueError(f"{name}: expected the exact Unicode 17.0.0 source digest")
    return raw.decode("utf-8").splitlines()


def merge_ranges(ranges):
    result = []
    for low, high in sorted(ranges):
        if not 0 <= low <= high <= 0x10FFFF:
            raise ValueError("invalid Unicode range")
        if result and low <= result[-1][1] + 1:
            result[-1] = (result[-1][0], max(high, result[-1][1]))
        else:
            result.append((low, high))
    return result


def generate(directory):
    categories = {"L": [], "N": []}
    first = None
    for line in read_source(directory, "UnicodeData.txt"):
        fields = line.split(";")
        point, name, category = int(fields[0], 16), fields[1], fields[2]
        if name.endswith(", First>"):
            if first is not None:
                raise ValueError("nested Unicode range")
            first = (point, name[:-8], category)
            continue
        if name.endswith(", Last>"):
            if first is None or (name[:-7], category) != first[1:]:
                raise ValueError("unmatched Unicode range")
            low = first[0]
            first = None
        else:
            if first is not None:
                raise ValueError("unterminated Unicode range")
            low = point
        if category[0] in categories:
            categories[category[0]].append((low, point))
    if first is not None:
        raise ValueError("unterminated final Unicode range")

    whitespace = []
    for line in read_source(directory, "PropList.txt"):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        points, property_name = (part.strip() for part in line.split(";"))
        if property_name == "White_Space":
            ends = points.split("..")
            whitespace.append((int(ends[0], 16), int(ends[-1], 16)))

    folding = {}
    for line in read_source(directory, "CaseFolding.txt"):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        source, status, target, _ = (part.strip() for part in line.split(";"))
        if status not in ("C", "S"):
            continue
        point = int(source, 16)
        target = int(target, 16)
        if point in folding or not 0 <= target <= 0x10FFFF or 0xD800 <= target <= 0xDFFF:
            raise ValueError("invalid default simple case fold")
        folding[point] = target

    out = [
        "//! Frozen Unicode 17.0.0 properties for the two named pretokenizers.",
        "//! Generated by tools/generate_unicode17_tables.py; no runtime data lookup.",
        "//! Upstream: https://www.unicode.org/Public/17.0.0/ucd/",
        "//! Copyright © 1991–2026 Unicode, Inc. Unicode License V3; see",
        "//! third_party/unicode/LICENSE.txt for the complete permission notice.",
    ]
    for name, digest in SOURCES.items():
        out.append(f"//! {name} SHA-256: {digest}")
    out.extend([
        "", "pub(super) const VERSION: (u8, u8, u8) = (17, 0, 0);", "",
        "pub(super) fn is_letter(c: char) -> bool { in_ranges(LETTERS, c) }",
        "pub(super) fn is_number(c: char) -> bool { in_ranges(NUMBERS, c) }",
        "pub(super) fn is_white_space(c: char) -> bool { in_ranges(WHITE_SPACE, c) }", "",
        "fn in_ranges(ranges: &[(u32, u32)], c: char) -> bool {",
        "    let point = u32::from(c);",
        "    let after = ranges.partition_point(|&(low, _)| low <= point);",
        "    after.checked_sub(1).is_some_and(|index| point <= ranges[index].1)",
        "}", "",
        "pub(super) fn fold_simple(c: char) -> char {",
        "    match SIMPLE_FOLD.binary_search_by_key(&u32::from(c), |&(source, _)| source) {",
        "        Ok(index) => SIMPLE_FOLD[index].1,",
        "        Err(_) => c,",
        "    }",
        "}", "",
    ])
    for name, ranges in (("LETTERS", categories["L"]), ("NUMBERS", categories["N"]),
                         ("WHITE_SPACE", whitespace)):
        out.append(f"const {name}: &[(u32, u32)] = &[")
        for low, high in merge_ranges(ranges):
            out.append(f"    (0x{low:X}, 0x{high:X}),")
        out.extend(["];", ""])
    out.append("const SIMPLE_FOLD: &[(u32, char)] = &[")
    for source, target in sorted(folding.items()):
        out.append(f"    (0x{source:X}, '\\u{{{target:x}}}'),")
    out.extend(["];", ""])
    return "\n".join(out)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("ucd_directory", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(args.ucd_directory), encoding="utf-8")
