//! A selected learned release is evaluated through its ORIGINAL frame builder.
//! The actor supplies a canonical release intent, never replacement output.
use super::{ActionSpec, ActorError, ActorProposal, Cell, Disclosure, ElapsedTick,
    Error, FileActorPrecheckPort, FileActorSupervisor, FileOversight,
    FilePrecheckDisclosure, JournalError, Rc};
use super::super::{LearnedTextRelease, learned_intake::LearnedStreamAdmission};

pub(super) struct Release {
    selected: LearnedStreamAdmission,
    action: ActionSpec,
}

impl Release {
    pub(super) fn action(&self, proposal: &ActorProposal) -> Result<ActionSpec, ActorError> {
        // Precheck carries the independently selected CURRENT policy epoch;
        // Submit still uses its original zero-valued canonical envelope marker.
        // Every other intent byte and the shortened deadline must match exactly.
        let mut intent = proposal.clone();
        intent.expected_policy_epoch = 0;
        self.selected.check(self.selected.request(), &intent)?;
        let mut action = self.action.clone();
        action.deadline = proposal.deadline;
        Ok(action)
    }
}

impl FileActorSupervisor<FileOversight> {
    /// Disclose only the exact policy result for one completed ORIGINAL learned
    /// Message or receipt-grounded Finish. The same finite query/revision grant
    /// and wire apply, but raw-proposal disclosure remains unavailable here.
    ///
    /// The original builder fixes the complete cumulative frame, target, units
    /// and policy epoch. Query bytes cannot replace any of them, select another
    /// request/release, or extend the selected deadline. The generated bytes
    /// remain private. No source/clock read, request, journal event, helper or
    /// effect key is created. Any subsequent owner mutation retires the grant.
    pub fn disclose_learned_text_stream_precheck(&self, expected_revision: u64,
        disclosure: u64, queries: usize, request: u64, release: LearnedTextRelease,
        latest_deadline: ElapsedTick,
    ) -> Result<(FileActorPrecheckPort, FilePrecheckDisclosure), JournalError> {
        if disclosure == 0 || queries == 0 { return Err(Error::InvalidInput.into()); }
        if queries > super::MAX_PRECHECK_QUERIES { return Err(Error::Limit.into()); }
        let selected = LearnedStreamAdmission::new(request, release, latest_deadline)?;
        let owner = self.owner.try_borrow().map_err(|_| JournalError::Unavailable)?;
        if owner.host.storage_failure().is_some() { return Err(JournalError::Unavailable); }
        if owner.host.revision() != expected_revision { return Err(Error::Stale.into()); }
        let (projection, action) = owner.host.learned_actor_precheck_projection(
            request, release, latest_deadline)?;
        let grant = Rc::new(Disclosure { id: disclosure, remaining: Cell::new(queries),
            projection, cache: None, learned: Some(Release { selected, action }) });
        let port = FileActorPrecheckPort { owner: Rc::downgrade(&self.owner),
            disclosure: Rc::downgrade(&grant) };
        Ok((port, FilePrecheckDisclosure { disclosure: grant }))
    }
}
