//! Exact policy disclosure for one original native-text Message or Finish.
//! The selected actor intent names source data, never replacement output bytes.
use super::{
    ActionSpec, ActorError, ActorProposal, Cell, Disclosure, Error, FileActorPrecheckPort,
    FileActorSupervisor, FileOversight, FilePrecheckDisclosure, JournalError, Rc,
};

pub(super) struct Release {
    intent: ActorProposal,
    action: ActionSpec,
}

impl Release {
    pub(super) fn action(&self, proposal: &ActorProposal) -> Result<ActionSpec, ActorError> {
        if proposal.target != self.intent.target
            || proposal.payload != self.intent.payload
            || proposal.units != self.intent.units
            || proposal.deadline.0 == 0
            || proposal.deadline > self.intent.deadline
        {
            return Err(ActorError::MalformedProposal);
        }
        // The common precheck boundary separately compares the query's policy
        // epoch with the original captured epoch, returning typed Stale data.
        let mut action = self.action.clone();
        action.deadline = proposal.deadline;
        Ok(action)
    }
}

impl FileActorSupervisor<FileOversight> {
    /// Disclose exact predicates for ONE independently selected native generated
    /// message or explicit Finish. `intent` must use the original
    /// `FileGeneratedTextActorPort::encode_message` or `encode_finish` encoding.
    /// The native builder fixes every generated byte, cumulative prior message,
    /// boundary and full-frame charge; the 32-byte source reference is never the
    /// action evaluated by policy. A query may only shorten the selected deadline.
    ///
    /// No inference, sampling, source/clock observation, admission snapshot, actor
    /// request, journal event or publication key is created or consumed. The
    /// original finite query grant expires on any owner transition and cannot
    /// survive replacement, loss or revocation. Actual submission still performs
    /// fresh source admission and requires independent helper and human review.
    pub fn disclose_generated_text_precheck(
        &self,
        expected_revision: u64,
        disclosure: u64,
        queries: usize,
        request: u64,
        intent: &ActorProposal,
    ) -> Result<(FileActorPrecheckPort, FilePrecheckDisclosure), JournalError> {
        if disclosure == 0 || queries == 0 || intent.deadline.0 == 0 {
            return Err(Error::InvalidInput.into());
        }
        if queries > super::MAX_PRECHECK_QUERIES {
            return Err(Error::Limit.into());
        }
        let message = super::super::generated::decode(request, intent).map_err(|error| {
            JournalError::Contract(match error {
                ActorError::Capacity => Error::Limit,
                _ => Error::InvalidInput,
            })
        })?;
        let owner = self
            .owner
            .try_borrow()
            .map_err(|_| JournalError::Unavailable)?;
        if owner.host.storage_failure().is_some() {
            return Err(JournalError::Unavailable);
        }
        if owner.host.revision() != expected_revision {
            return Err(Error::Stale.into());
        }
        let (projection, action) =
            owner
                .host
                .generated_actor_precheck_projection(request, intent, message.as_ref())?;
        let grant = Rc::new(Disclosure {
            id: disclosure,
            remaining: Cell::new(queries),
            projection,
            cache: None,
            release: Some(super::Release::Generated(Release {
                intent: intent.clone(),
                action,
            })),
        });
        let port = FileActorPrecheckPort {
            owner: Rc::downgrade(&self.owner),
            disclosure: Rc::downgrade(&grant),
            issuer: owner.host.journal_tail_identity(),
            scope: grant.projection.scope,
        };
        Ok((port, FilePrecheckDisclosure { disclosure: grant }))
    }
}
