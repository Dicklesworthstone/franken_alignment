fn execute() -> Result<(), String> {
    let root = workspace_root()?;
    let args: Vec<_> = env::args().skip(1).collect();
    match args.as_slice() {
        [command] if command == "check" => {
            check_lock(&root)?;
            check_source(&root)?;
            check_toolchain(&root)?;
            let manifest = check_source_snapshot(&root)?;
            check_admission(&root)?;
            check_registries(&root)?;
            check_concordance(&root, &manifest)?;
            check_system_map(&root)?;
            check_prose(&root)?;
            run(&root, "cargo", &["fmt", "--all", "--check"])?;
            run(&root, "cargo", &["check", "--workspace", "--all-targets", "--frozen"])?;
            run(&root, "cargo", &["clippy", "--workspace", "--all-targets", "--frozen", "--", "-D", "warnings"])?;
            run(&root, "cargo", &["test", "--workspace", "--all-targets", "--frozen"])?;
            run(&root, "cargo", &["test", "--workspace", "--doc", "--frozen"])?;
            println!("PASS local_reference_gate; not a production-readiness or signed-release claim");
            Ok(())
        }
        [command] if command == "inventory" => {
            check_lock(&root)?;
            check_source(&root)?;
            println!("INVENTORY ONLY: compilation, tests, source freezing and release verification were not performed by this command");
            Ok(())
        }
        [command] if command == "concordance-check" => {
            let manifest = check_source_snapshot(&root)?;
            check_concordance(&root, &manifest)
        }
        [command] if command == "prose-check" => {
            let _manifest = check_source_snapshot(&root)?;
            check_prose(&root)
        }
        [command] if command == "system-map-check" => {
            let _manifest = check_source_snapshot(&root)?;
            check_system_map(&root)
        }
        [command] if command == "release-check" => {
            Err("Release blocked: no qualified production broker, frozen release toolchain, foundation closure, target matrix or signed proof closure exists yet.".into())
        }
        _ => Err("Usage: cargo xtask check | concordance-check | system-map-check | prose-check | inventory | release-check".into()),
    }
}

fn main() -> ExitCode {
    match execute() {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("FAIL: {error}");
            ExitCode::FAILURE
        }
    }
}
